export function getIkeaDrawerById(id) {
  return IKEA_DRAWERS.find((d) => d.id === id) || null;
}

export function searchIkeaDrawers(query, clearanceMm = 1) {
  const norm = (query || '').trim().toLowerCase().replace(/×/g, 'x');
  if (!norm) return IKEA_DRAWERS;
  const tokens = norm.split(/\s+/).filter(Boolean);
  return IKEA_DRAWERS.filter((item) => {
    const cols = Math.floor((Math.max(0, item.widthMm - clearanceMm) + 1e-6) / 42);
    const rows = Math.floor((Math.max(0, item.depthMm - clearanceMm) + 1e-6) / 42);
    const haystack = [
      item.name,
      item.shortName || '',
      item.series,
      item.category,
      `${item.widthMm}x${item.depthMm}`,
      `${item.widthMm} x ${item.depthMm}`,
      `${cols}x${rows}`,
      `${cols}x${rows}u`,
      item.heightNote || '',
      item.note || '',
      item.keywords || '',
    ]
      .join(' ')
      .toLowerCase()
      .replace(/×/g, 'x');
    return tokens.every((tok) => haystack.includes(tok));
  });
}
